-- Owner-only investment portfolio: the transaction ledger is the single source of truth.
-- Holdings, average cost, cash and loan balances are derived by replaying portfolio_transactions.

create table portfolio_accounts (
    id bigint generated by default as identity,
    name varchar(100) not null,
    institution varchar(100) not null,
    account_type varchar(30) not null,
    account_number_last4 varchar(4),
    interest_rate numeric(7, 4),
    monthly_payment numeric(19, 2),
    repayment_type varchar(30),
    opened_at date,
    maturity_date date,
    closed_at date,
    display_order integer not null default 0,
    memo varchar(500),
    created_at timestamp not null,
    updated_at timestamp not null,
    constraint pk_portfolio_accounts primary key (id),
    constraint ck_portfolio_accounts_monthly_payment check (monthly_payment is null or monthly_payment >= 0)
);

create table portfolio_instruments (
    id bigint generated by default as identity,
    symbol varchar(20) not null,
    name varchar(100) not null,
    market varchar(10) not null,
    trading_currency varchar(3) not null,
    instrument_type varchar(10) not null,
    underlying_asset_class varchar(20) not null,
    exposure_region varchar(10) not null,
    fx_hedged boolean not null,
    tax_type varchar(30) not null,
    price_source varchar(10) not null,
    active boolean not null,
    created_at timestamp not null,
    updated_at timestamp not null,
    constraint pk_portfolio_instruments primary key (id),
    constraint uk_portfolio_instruments_market_symbol unique (market, symbol)
);

create table portfolio_transactions (
    id bigint generated by default as identity,
    account_id bigint not null,
    type varchar(20) not null,
    trade_date date not null,
    instrument_id bigint,
    quantity numeric(28, 8),
    price numeric(19, 4),
    fx_rate numeric(19, 6) not null default 1,
    amount numeric(19, 2) not null,
    fee numeric(19, 2) not null default 0,
    tax numeric(19, 2) not null default 0,
    transfer_group_id uuid,
    memo varchar(500),
    created_at timestamp not null,
    updated_at timestamp not null,
    constraint pk_portfolio_transactions primary key (id),
    constraint fk_portfolio_transactions_account_id foreign key (account_id) references portfolio_accounts (id),
    constraint fk_portfolio_transactions_instrument_id foreign key (instrument_id) references portfolio_instruments (id),
    constraint ck_portfolio_transactions_amounts check (amount >= 0 and fee >= 0 and tax >= 0 and fx_rate > 0),
    constraint ck_portfolio_transactions_trade check (
        type not in ('BUY', 'SELL')
        or (instrument_id is not null and quantity > 0 and price > 0)
    )
);

create index idx_portfolio_transactions_account_date
    on portfolio_transactions (account_id, trade_date, id);

create index idx_portfolio_transactions_transfer_group
    on portfolio_transactions (transfer_group_id);

create table portfolio_manual_valuations (
    id bigint generated by default as identity,
    account_id bigint not null,
    valuation_date date not null,
    amount numeric(19, 2) not null,
    memo varchar(500),
    created_at timestamp not null,
    updated_at timestamp not null,
    constraint pk_portfolio_manual_valuations primary key (id),
    constraint fk_portfolio_manual_valuations_account_id foreign key (account_id) references portfolio_accounts (id),
    constraint uk_portfolio_manual_valuations_account_date unique (account_id, valuation_date),
    constraint ck_portfolio_manual_valuations_amount check (amount >= 0)
);
