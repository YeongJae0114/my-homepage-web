-- Price / FX history and daily snapshots. One row per instrument (or currency) per day:
-- automatic collectors never overwrite a MANUAL row (the owner's correction wins).

create table portfolio_prices (
    id bigint generated by default as identity,
    instrument_id bigint not null,
    price_date date not null,
    close_price numeric(19, 4) not null,
    source varchar(10) not null,
    is_final boolean not null,
    captured_at timestamp not null,
    constraint pk_portfolio_prices primary key (id),
    constraint fk_portfolio_prices_instrument_id foreign key (instrument_id) references portfolio_instruments (id),
    constraint uk_portfolio_prices_instrument_date unique (instrument_id, price_date),
    constraint ck_portfolio_prices_close check (close_price > 0)
);

create table portfolio_fx_rates (
    id bigint generated by default as identity,
    currency varchar(3) not null,
    rate_date date not null,
    rate_to_krw numeric(19, 6) not null,
    source varchar(10) not null,
    captured_at timestamp not null,
    constraint pk_portfolio_fx_rates primary key (id),
    constraint uk_portfolio_fx_rates_currency_date unique (currency, rate_date),
    constraint ck_portfolio_fx_rates_rate check (rate_to_krw > 0)
);

create table portfolio_snapshots (
    id bigint generated by default as identity,
    snapshot_date date not null,
    cash_equivalent numeric(19, 2) not null,
    investment numeric(19, 2) not null,
    pension_insurance numeric(19, 2) not null,
    total_assets numeric(19, 2) not null,
    total_liabilities numeric(19, 2) not null,
    net_worth numeric(19, 2) not null,
    scope_value numeric(19, 2) not null,
    scope_net_flow numeric(19, 2) not null,
    price_as_of date,
    computed_at timestamp not null,
    constraint pk_portfolio_snapshots primary key (id),
    constraint uk_portfolio_snapshots_date unique (snapshot_date)
);
